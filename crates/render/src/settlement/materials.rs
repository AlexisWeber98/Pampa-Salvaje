//! The settlements' PBR materials: one shared material per surface.
//!
//! The textured surfaces wear the CC0 sets in
//! `assets/textures/buildings/<set>/` (ambientCG and Poly Haven, plus our
//! own thatch; see that folder's CREDITS.md): `color`, `normal_gl`,
//! `roughness` and, where shipped, `ao`, loaded through the
//! [`AssetServer`] with a repeating, anisotropic sampler. The normal maps
//! are OpenGL (+Y), as Bevy reads them.
//!
//! Bevy's `metallic_roughness_texture` reads roughness from green and
//! metallic from blue, while the shipped `roughness.jpg` is greyscale. So
//! once a texture has loaded, [`finish_textures`] repacks the roughness map
//! in place (grey into green, full blue, and the material's own `metallic`
//! scales it per surface) and gives every map its mip chain, built on the
//! CPU once: JPEGs load with a single level, which shimmers at a distance.
//!
//! Without an asset server (headless tests) or when a set's files are
//! missing, the surface falls back to a plain colour of the same look.

use std::path::Path;

use bevy::asset::RenderAssetUsages;
use bevy::image::{
    ImageAddressMode, ImageFilterMode, ImageLoaderSettings, ImageSampler, ImageSamplerDescriptor,
};
use bevy::prelude::*;
use bevy::render::render_resource::TextureFormat;

use crate::AssetRoot;

/// Where the building texture sets live, under the [`AssetRoot`].
pub const TEXTURE_DIR: &str = "textures/buildings";

/// What a piece of a settlement is made of. Each is one shared material.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Surface {
    /// Adobe walls: mud plaster (`clay_plaster`).
    Adobe,
    /// Whitewashed lime plaster (`plaster_003`).
    Whitewash,
    /// Exposed brick (`brick_wall_02`), and the brick of a well's curb.
    Brick,
    /// Old, rust-streaked corrugated roofing (`corrugated_iron_02`).
    OldIron,
    /// Bright galvanised corrugated sheet (`corrugated_iron`): tanks.
    Galvanised,
    /// Weathered boards (`brown_planks_05`): doors, shutters, rails, posts.
    Planks,
    /// Paja roofs and haystacks (`thatch`, generated by us).
    Thatch,
    /// The tracks' dry mud (`brown_mud_dry`), feathered into the grass.
    Mud,
    /// Trodden patios and yards (`dry_ground_01`), feathered too.
    Yard,
    /// The dark inside of an open doorway or window.
    Recess,
    /// Painted steel: the molino's tower, the gallery's iron posts.
    Steel,
    /// Thin galvanised sheet: the molino's blades and vane.
    Sheet,
    /// Still water in a tank, trough or well.
    Water,
}

impl Surface {
    /// Every surface, in order.
    pub const ALL: [Surface; 13] = [
        Surface::Adobe,
        Surface::Whitewash,
        Surface::Brick,
        Surface::OldIron,
        Surface::Galvanised,
        Surface::Planks,
        Surface::Thatch,
        Surface::Mud,
        Surface::Yard,
        Surface::Recess,
        Surface::Steel,
        Surface::Sheet,
        Surface::Water,
    ];

    /// The texture set it wears, if any.
    pub fn set(self) -> Option<&'static str> {
        Some(match self {
            Self::Adobe => "clay_plaster",
            Self::Whitewash => "plaster_003",
            Self::Brick => "brick_wall_02",
            Self::OldIron => "corrugated_iron_02",
            Self::Galvanised => "corrugated_iron",
            Self::Planks => "brown_planks_05",
            Self::Thatch => "thatch",
            Self::Mud => "brown_mud_dry",
            Self::Yard => "dry_ground_01",
            Self::Recess | Self::Steel | Self::Sheet | Self::Water => return None,
        })
    }

    /// Meters per texture repeat: the world size one texture covers.
    pub fn tile(self) -> f32 {
        match self {
            Self::Brick | Self::Planks | Self::Thatch => 2.0,
            Self::OldIron | Self::Galvanised => 2.0,
            Self::Adobe | Self::Whitewash | Self::Mud => 2.5,
            Self::Yard => 3.0,
            Self::Recess | Self::Steel | Self::Sheet | Self::Water => 1.0,
        }
    }

    /// Its plain colour (sRGB): the whole look without textures, and the
    /// tint over them.
    fn color(self, textured: bool) -> Color {
        if textured {
            // A touch of the 1919 dust over the clean scans.
            return match self {
                Self::Whitewash => Color::srgb(0.97, 0.95, 0.90),
                Self::Galvanised => Color::srgb(0.92, 0.93, 0.94),
                _ => Color::WHITE,
            };
        }
        let (r, g, b) = match self {
            Self::Adobe => (0.62, 0.50, 0.38),
            Self::Whitewash => (0.88, 0.86, 0.80),
            Self::Brick => (0.58, 0.33, 0.24),
            Self::OldIron => (0.47, 0.38, 0.31),
            Self::Galvanised => (0.64, 0.65, 0.64),
            Self::Planks => (0.42, 0.33, 0.24),
            Self::Thatch => (0.66, 0.56, 0.36),
            Self::Mud => (0.50, 0.40, 0.29),
            Self::Yard => (0.60, 0.52, 0.40),
            Self::Recess => (0.05, 0.045, 0.04),
            Self::Steel => (0.24, 0.24, 0.25),
            Self::Sheet => (0.70, 0.71, 0.71),
            Self::Water => (0.10, 0.13, 0.13),
        };
        Color::srgb(r, g, b)
    }

    /// Roughness, metallic and reflectance.
    fn pbr(self) -> (f32, f32, f32) {
        match self {
            Self::Galvanised => (1.0, 0.75, 0.5),
            Self::OldIron => (1.0, 0.35, 0.4),
            Self::Sheet => (0.45, 0.8, 0.5),
            Self::Steel => (0.6, 0.6, 0.5),
            Self::Water => (0.08, 0.0, 0.5),
            Self::Recess => (1.0, 0.0, 0.1),
            _ => (1.0, 0.0, 0.3),
        }
    }

    /// The decals laid over the ground blend into it by vertex alpha.
    fn blended(self) -> bool {
        matches!(self, Self::Mud | Self::Yard)
    }
}

/// How a texture map is post-processed once loaded.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Map {
    /// Colour, normal or occlusion: mips only.
    Plain,
    /// The greyscale roughness map: repacked into green, then mips.
    Roughness,
}

/// One shared material per [`Surface`].
#[derive(Resource, Debug, Clone)]
pub struct SettlementMaterials {
    materials: Vec<(Surface, Handle<StandardMaterial>)>,
}

impl SettlementMaterials {
    /// The material of `surface`.
    pub fn get(&self, surface: Surface) -> Handle<StandardMaterial> {
        self.materials
            .iter()
            .find(|(s, _)| *s == surface)
            .map(|(_, m)| m.clone())
            .expect("every surface has a material")
    }
}

/// Texture maps still waiting for their one-time post-processing.
#[derive(Resource, Debug, Default)]
pub(crate) struct PendingTextures(Vec<(Handle<Image>, Map)>);

/// Builds the shared materials, starting the texture loads when an asset
/// server and an asset root are there.
pub(crate) fn setup_materials(
    mut commands: Commands,
    root: Option<Res<AssetRoot>>,
    server: Option<Res<AssetServer>>,
    mut materials: ResMut<Assets<StandardMaterial>>,
) {
    let mut pending = Vec::new();
    let mut textured = 0;
    let built = Surface::ALL
        .iter()
        .map(|&surface| {
            let maps = match (surface.set(), root.as_deref(), server.as_deref()) {
                (Some(set), Some(root), Some(server)) => {
                    load_set(server, &root.0, set, &mut pending)
                }
                _ => None,
            };
            textured += maps.is_some() as usize;
            (surface, materials.add(material(surface, maps)))
        })
        .collect();
    if root.is_some() && server.is_some() {
        info!(
            "settlement materials: {} surfaces, {textured} textured",
            Surface::ALL.len()
        );
    }
    commands.insert_resource(SettlementMaterials { materials: built });
    commands.insert_resource(PendingTextures(pending));
}

/// A set's loading maps: colour, normal, roughness and occlusion.
struct Maps {
    color: Handle<Image>,
    normal: Handle<Image>,
    roughness: Handle<Image>,
    occlusion: Option<Handle<Image>>,
}

/// Starts loading texture set `set`, or warns and returns `None` when its
/// colour, normal or roughness file is missing.
fn load_set(
    server: &AssetServer,
    root: &Path,
    set: &str,
    pending: &mut Vec<(Handle<Image>, Map)>,
) -> Option<Maps> {
    let dir = format!("{TEXTURE_DIR}/{set}");
    let path = |name: &str| format!("{dir}/{name}.jpg");
    let missing: Vec<&str> = ["color", "normal_gl", "roughness"]
        .into_iter()
        .filter(|name| !root.join(path(name)).is_file())
        .collect();
    if !missing.is_empty() {
        warn!("building textures {dir} not loaded (missing {missing:?}); drawing plain colour");
        return None;
    }
    let mut load = |name: &str, srgb: bool, map: Map| {
        let handle: Handle<Image> = server
            .load_builder()
            .with_settings(move |s: &mut ImageLoaderSettings| {
                s.is_srgb = srgb;
                s.sampler = ImageSampler::Descriptor(repeating());
                // Kept on the CPU until `finish_textures` has repacked it
                // and built its mips; then it lives on the GPU only.
                s.asset_usage = RenderAssetUsages::default();
            })
            .load(path(name));
        pending.push((handle.clone(), map));
        handle
    };
    let color = load("color", true, Map::Plain);
    let normal = load("normal_gl", false, Map::Plain);
    let roughness = load("roughness", false, Map::Roughness);
    let occlusion = root
        .join(path("ao"))
        .is_file()
        .then(|| load("ao", false, Map::Plain));
    Some(Maps {
        color,
        normal,
        roughness,
        occlusion,
    })
}

fn repeating() -> ImageSamplerDescriptor {
    ImageSamplerDescriptor {
        address_mode_u: ImageAddressMode::Repeat,
        address_mode_v: ImageAddressMode::Repeat,
        mag_filter: ImageFilterMode::Linear,
        min_filter: ImageFilterMode::Linear,
        mipmap_filter: ImageFilterMode::Linear,
        anisotropy_clamp: 8,
        ..default()
    }
}

/// The material of `surface`, wearing `maps` when they are loading.
fn material(surface: Surface, maps: Option<Maps>) -> StandardMaterial {
    let (perceptual_roughness, metallic, reflectance) = surface.pbr();
    let mut material = StandardMaterial {
        base_color: surface.color(maps.is_some()),
        perceptual_roughness,
        metallic,
        reflectance,
        ..default()
    };
    if surface.blended() {
        // Laid over the ground like the road: blended by vertex alpha and
        // pulled a little toward the camera so it never fights the terrain.
        material.alpha_mode = AlphaMode::Blend;
        material.depth_bias = 2.0;
    }
    if let Some(maps) = maps {
        material.base_color_texture = Some(maps.color);
        material.normal_map_texture = Some(maps.normal);
        material.metallic_roughness_texture = Some(maps.roughness);
        material.occlusion_texture = maps.occlusion;
    }
    material
}

/// Post-processes every texture map that has just loaded, once: the
/// roughness map repacked for Bevy, and every map given its mips. Runs
/// before the render world first copies the image, in the frame it
/// arrives. Maps that failed to load are dropped (the asset server has
/// logged why).
pub(crate) fn finish_textures(
    mut pending: ResMut<PendingTextures>,
    server: Option<Res<AssetServer>>,
    images: Option<ResMut<Assets<Image>>>,
) {
    let Some(mut images) = images else {
        return;
    };
    if pending.0.is_empty() {
        return;
    }
    pending.0.retain(|(handle, map)| {
        if let Some(mut image) = images.get_mut(handle) {
            finish(&mut image, *map);
            return false;
        }
        !server
            .as_deref()
            .is_some_and(|s| s.load_state(handle).is_failed())
    });
}

/// Repacks and mips one loaded map in place; leaves anything but plain
/// RGBA8 (what the JPEG loader makes) as it is.
fn finish(image: &mut Image, map: Map) {
    let (w, h) = (image.width(), image.height());
    let format = image.texture_descriptor.format;
    let rgba8 = matches!(
        format,
        TextureFormat::Rgba8Unorm | TextureFormat::Rgba8UnormSrgb
    );
    let Some(data) = image.data.take() else {
        return;
    };
    if !rgba8 || image.texture_descriptor.mip_level_count != 1 || data.len() != (w * h * 4) as usize
    {
        image.data = Some(data);
        return;
    }
    let mut data = data;
    if map == Map::Roughness {
        repack_roughness(&mut data);
    }
    let (data, levels) = with_mips(w, h, data);
    image.data = Some(data);
    image.texture_descriptor.mip_level_count = levels;
    image.asset_usage = RenderAssetUsages::RENDER_WORLD;
}

/// Greyscale roughness (in red, green and blue) as Bevy's
/// metallic-roughness map: roughness in green, full metallic in blue (the
/// material's `metallic` scales it), red and alpha untouched.
pub(crate) fn repack_roughness(rgba: &mut [u8]) {
    for px in rgba.as_chunks_mut::<4>().0 {
        px[1] = px[0];
        px[2] = 255;
    }
}

/// `rgba` (`w`×`h` RGBA8) followed by its box-filtered mip levels down to
/// 1×1, and how many levels there are.
pub(crate) fn with_mips(w: u32, h: u32, rgba: Vec<u8>) -> (Vec<u8>, u32) {
    let mut data = rgba;
    let (mut w, mut h) = (w as usize, h as usize);
    let mut start = 0;
    let mut levels = 1;
    while w > 1 || h > 1 {
        let (nw, nh) = ((w / 2).max(1), (h / 2).max(1));
        let mut next = Vec::with_capacity(nw * nh * 4);
        for y in 0..nh {
            for x in 0..nw {
                for c in 0..4 {
                    let mut sum = 0u32;
                    for (dx, dy) in [(0, 0), (1, 0), (0, 1), (1, 1)] {
                        let (sx, sy) = ((2 * x + dx).min(w - 1), (2 * y + dy).min(h - 1));
                        sum += data[start + (sy * w + sx) * 4 + c] as u32;
                    }
                    next.push(((sum + 2) / 4) as u8);
                }
            }
        }
        start = data.len();
        data.extend(next);
        (w, h) = (nw, nh);
        levels += 1;
    }
    (data, levels)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roughness_moves_to_green_with_full_blue() {
        let mut px = vec![200, 200, 200, 255, 30, 30, 30, 255];
        repack_roughness(&mut px);
        assert_eq!(px, [200, 200, 255, 255, 30, 30, 255, 255]);
    }

    #[test]
    fn mips_run_down_to_one_texel_and_average() {
        let (data, levels) = with_mips(4, 2, vec![100; 4 * 2 * 4]);
        // 4×2, 2×1, 1×1.
        assert_eq!(levels, 3);
        assert_eq!(data.len(), (8 + 2 + 1) * 4);
        assert!(data.iter().all(|&b| b == 100));
    }

    #[test]
    fn every_textured_surface_names_a_shipped_set() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets");
        for surface in Surface::ALL {
            let Some(set) = surface.set() else {
                continue;
            };
            for map in ["color", "normal_gl", "roughness"] {
                let file = root.join(format!("{TEXTURE_DIR}/{set}/{map}.jpg"));
                assert!(file.is_file(), "{}", file.display());
            }
        }
    }
}
